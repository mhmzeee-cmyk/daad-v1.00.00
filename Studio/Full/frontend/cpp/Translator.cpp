Translator::Translator(QObject* parent) : QObject(parent) {
    loadTranslations("ar");
    loadTranslations("en");
}

QStringList Translator::availableLanguages() const {
    QStringList codes;
    for (const auto& lang : languageList()) {
        codes << lang.code;
    }
    return codes;
}

void Translator::setCurrentLanguage(const QString& lang) {
    if (m_currentLang != lang) {
        m_currentLang = lang;
        m_langVersion++;
        loadTranslations(lang);
        emit languageChanged();
    }
}

QString Translator::translate(const QString& key) const {
    auto it = m_translations.find(m_currentLang);
    if (it != m_translations.end()) {
        auto val = it->find(key);
        if (val != it->end()) return *val;
    }
    auto fallback = m_translations.find("en");
    if (fallback != m_translations.end()) {
        auto val = fallback->find(key);
        if (val != fallback->end()) return *val;
    }
    return key;
}

