async function main() {
  console.log('Updating ' + updates.length + ' challenges...');
  for (const u of updates) {
    try {
      await prisma.challenge.update({
        where: { id: u.id },
        data: {
          title: u.title,
          description: u.description,
          starterCode: u.starterCode,
          expectedOutput: u.expectedOutput,
          published: true,
        },
      });
      console.log('OK: ' + u.title);
    } catch (err) {
      console.error('FAIL: ' + u.title + ' - ' + err.message);
    }
  }
  console.log('Done!');
  await prisma.$disconnect();
}

main();
